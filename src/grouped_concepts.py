def apply_grouped(study):
    updated=[]
    for p in study['knowledge']:
        guide=GROUPS.get(p['title'])
        if not guide:continue
        p['studyGuide']=deepcopy(guide)
        p['reasoning']=guide['distinction']
        if guide.get('authority'):p['authority']=guide['authority'];p['checkedAt']='2026-10-06'
        if p['title']=='四项基本原则':
            p['statement']='四项基本原则的具体内容是：'+ '；'.join(m[0] for m in FOUR)+'。四项基本原则是立国之本，是党和国家生存发展的政治基石。'
        if p['title']=='外交和平共处五项原则':
            p.setdefault('originalStatement',p['statement'])
            p['statement']='和平共处五项原则：互相尊重主权和领土完整、互不侵犯、互不干涉内政、平等互利、和平共处。'
            p['source']='tricolor';p['page']=173
            p['chapters']=[c['id'] for c in study['curriculum'] if c['source']=='tricolor' and c['start']<=173<=c['end']]
            p['correction']='已纠正原整理中将勋章内容与外交原则错配的问题，按资料第173页及外交部资料核对。'
        if p['title']=='全球四大导航系统':
            p['statement']='全球四大卫星导航系统是中国北斗、美国GPS、俄罗斯格洛纳斯、欧洲伽利略。'
            
            if not p.get('questionIds'):
                p['status']='needs-question';p['reviewReason']='具体内容已按卫星导航系统主管部门资料核对，尚未另编完整练习。'
        updated.append(p['id'])
    points={p['id']:p for p in study['knowledge']}
    for q in study['questions']:
        p=points.get(q.get('concept'));guide=p.get('studyGuide') if p else None
        if not guide:continue
        q['extension']='具体内容：'+'；'.join(m['name']+'：'+m['meaning'].rstrip('。') for m in guide['members'])+'。易混辨析：'+guide['distinction']+' 回忆方法：'+guide['recall']
    return updated
