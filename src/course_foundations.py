def apply_foundations(study,topics):
    by_topic={t['id']:t for t in topics}
    for t in topics:t['foundations']=[]
    for g in FOUNDATIONS:
        for tid in g['topicIds']:
            if tid in by_topic:by_topic[tid]['foundations'].append(deepcopy(g))
    # Guides on referential point pages must include the prerequisites too.
    for p in study['knowledge']:
        if '四项基本原则' in p['statement'] and p['title']!='四项基本原则':
            p['prerequisites']=[deepcopy(FOUNDATIONS[0])]
    study['foundationCount']=len(FOUNDATIONS)
