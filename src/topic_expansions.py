def compile_topics(study):
    """Use heading/prompt first. Every question gets a topical lesson or a clear unit overview."""
    chapters={c['id']:c for c in study['curriculum']}
    points={p['id']:p for p in study['knowledge']}
    candidates={m['id']:[dict(t) for t in TOPICS if t['module']==m['id']] for m in study['modules']}
    result=[]
    for module in study['modules']:
        guide=study['guides'][module['id']]
        # An honest broad overview handles uncommon or OCR fragments without mislabelling them.
        fallback=dict(id='topic-'+module['id']+'-overview',module=module['id'],title=module['title']+'知识框架',
            keywords=[],overview=guide['thesis'],diagram=[dict(label=r[0],text='；'.join(r[1:])) for r in guide.get('compare',[])],
            connection=' '.join(guide['reasoning']),boundary=guide['method'],
            variant=' '.join(guide['case']),recall='先复述本题考点，再按上面的分类维度与相近概念对照。说明题干哪个条件决定答案。',layout='compare',overviewOnly=True)
        candidates[module['id']].append(fallback)
        result+=candidates[module['id']]
    # Persisted curation by stable point ID. Distractor wording cannot change associations.
    point_topics=json.loads((Path(__file__).parent/'course-topic-map.json').read_text())
    assert set(points)==set(point_topics), 'New knowledge requires an explicit course assignment'
    by_id={t['id']:t for t in result}
    for pid,tid in point_topics.items():
        assert tid in by_id and by_id[tid]['module']==points[pid]['module'], (pid,tid)
    question_topics={}
    question_topic_ids={}
    for q in study['questions']:
        ids=list(dict.fromkeys(point_topics[i] for i in q.get('pointIds',[]) if i in point_topics))
        assert ids, 'Question requires actual assessed point IDs: '+q['id']
        question_topic_ids[q['id']]=ids
        question_topics[q['id']]=ids[0]
    study['questionTopicIds']=question_topic_ids
    from reading_edition import PICTURE_PAGES
    images=json.loads((Path(__file__).parent/'reading-images.json').read_text())
    for t in result:
        t['pointIds']=[p['id'] for p in points.values() if point_topics[p['id']]==t['id']]
        t['questionIds']=[q['id'] for q in study['questions'] if t['id'] in question_topic_ids[q['id']]]
        refs=[]
        for p in (points[i] for i in t['pointIds']):
            if p.get('status')=='needs-review':continue
            ref=dict(source=p['source'],page=p['page'])
            if ref not in refs:refs.append(ref)
        # Even a question-only topic is tied to the provided material.
        for q in (q for q in study['questions'] if q['id'] in t['questionIds']):
            ref=dict(source=q['source'],page=q['page'])
            if ref not in refs:refs.append(ref)
        t['refs']=refs[:6]
        authorities=[]
        for item in [points[i] for i in t['pointIds']]+[q for q in study['questions'] if q['id'] in t['questionIds']]:
            url=item.get('authority')
            if url and url not in authorities:authorities.append(url)
        if t['module']=='m02':authorities.insert(0,'https://www.npc.gov.cn/wxzlhgb/c27214/gb2020/202006/P020230313538731037747.pdf')
        if t['module']=='m08':authorities.insert(0,'https://www.miit.gov.cn/xwdt/szyw/art/2020/art_6afb8ee6d07540dcacccbeb47dbc0fd4.html')
        if t['id']=='topic-new-era-framework':authorities.insert(0,'https://www.gov.cn/xinwen/2022-10/16/content_5718809.htm')
        t['authorities']=list(dict.fromkeys(authorities))[:3]
        t['sourceFigures']=[]
        for ref in refs:
            if ref['page'] in PICTURE_PAGES.get(ref['source'],set()):
                info=images.get(ref['source']+':'+str(ref['page']))
                if info:t['sourceFigures'].append(dict(info))
            if len(t['sourceFigures'])==2:break
        t['relatedTopicIds']=[x['id'] for x in candidates[t['module']] if x['id']!=t['id'] and not x.get('overviewOnly')]
        t['visualIds']=[v['id'] for v in study['visualReferences'] if any(point_topics.get(i)==t['id'] for i in v['pointIds'])]
        t.pop('keywords',None)
    from course_foundations import apply_foundations
    apply_foundations(study,result)
    return result,point_topics,question_topics


def write_diagrams(topics, public):
    """Export functional text diagrams, with the same wording as accessible HTML."""
    destination=public/'images/topics';destination.mkdir(parents=True,exist_ok=True)
    def wrap(text,limit=23):
        lines=[];line='';width=0
        for c in text:
            w=0.55 if ord(c)<128 else 1
            if width+w>limit:lines.append(line);line='';width=0
            line+=c;width+=w
        if line:lines.append(line)
        return lines
    for t in topics:
        cards=t['diagram']
        if not cards:continue
        column_count=1 if t['layout']=='timeline' else 2
        box_width=888 if column_count==1 else 432
        limit=49 if column_count==1 else 23
        groups=[cards[i:i+column_count] for i in range(0,len(cards),column_count)]
        y=116;elements=[]
        esc=html.escape
        for group in groups:
            height=max(92+28*(len(wrap(c['text'],limit))-1) for c in group)
            for index,c in enumerate(group):
                x=36+index*456
                elements.append(f'<rect x="{x}" y="{y}" width="{box_width}" height="{height}" rx="14" fill="#ffffff" stroke="#c7d7e9"/>')
                elements.append(f'<text x="{x+22}" y="{y+32}" fill="#24599b" font-size="20" font-weight="700">{esc(c["label"])}</text>')
                for n,line in enumerate(wrap(c['text'],limit)):
                    elements.append(f'<text x="{x+22}" y="{y+64+n*28}" fill="#354256" font-size="18">{esc(line)}</text>')
            y+=height+22
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="960" height="{y+42}" viewBox="0 0 960 {y+42}" role="img" aria-labelledby="title"><title id="title">{esc(t["title"])}知识框架</title><rect width="960" height="{y+42}" fill="#f5f8fc"/><g font-family="PingFang SC,Microsoft YaHei,Noto Sans CJK SC,sans-serif"><text x="36" y="50" fill="#183254" font-size="26" font-weight="700">{esc(t["title"])}</text><text x="36" y="86" fill="#576579" font-size="17">{("按时间排列；各节点的背景与影响需分别理解。" if t["layout"]=="timeline" else "分类对照；各组概念的条件与适用范围需分别辨析。")}</text>'+''.join(elements)+f'<text x="36" y="{y+20}" fill="#576579" font-size="15">公基学习台 · 依据提供资料整理，完整讲解与出处见专题页</text></g></svg>'
        (destination/(t['id']+'.svg')).write_text(svg,encoding='utf-8')
        t['diagramAsset']='images/topics/'+t['id']+'.svg'
