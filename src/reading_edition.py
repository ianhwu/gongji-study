def clean_blocks(text):
    """Retain content order; join only obvious wrapped prose, never OCR tables."""
    raw = text.splitlines()
    lines = []
    for i, original in enumerate(raw):
        line = re.sub(r'\s+', ' ', original).strip()
        if not line: continue
        if re.search(r'微信公众号|售后微信|资源微信|biguo|公共基础知识笔记[（(]|超格教育', line, re.I): continue
        if i >= len(raw)-4 and re.fullmatch(r'[-—\s]*\d{1,4}[-—\s]*',line): continue
        if re.fullmatch(r'[G©®|①]?\s*超格教育.*',line): continue
        lines.append(line)
    blocks=[]
    for line in lines:
        heading = bool(re.match(r'^(第[一二三四五六七八九十百\d]+[章部分节]|知识点[一二三四五六七八九十\d]|[一二三四五六七八九十]+[、．])',line)) and len(line)<62
        marker = bool(re.match(r'^(?:[（(]?[0-9一二三四五六七八九十]+[）).、．]|[①②③④⑤⑥⑦⑧⑨⑩]|Eg[.．]|例[：:]|超格提示|拓展补充)',line))
        kind='heading' if heading else 'note' if re.match(r'^(超格提示|拓展补充)',line) else 'item' if marker else 'paragraph'
        # A short cell is left alone. It could be a table header or diagram node.
        if kind=='paragraph' and blocks and blocks[-1]['type'] in ('paragraph','item') and len(blocks[-1]['text'])>=28 and len(line)>=14 and not re.search(r'[。！？；：:）》】]$',blocks[-1]['text']):
            blocks[-1]['text']+=line
        else: blocks.append(dict(type=kind,text=line))
    return blocks

def compile_editions(study,pages):
    notes=chapter_notes()
    chapters={}
    for c in study['curriculum']:
        g=study['guides'][c['module']]
        n=notes.get(c['id']) or dict(thesis=g['thesis'],route=g['method'],trap='先辨析概念的适用条件与范围，再与相邻考点比较。',recall=f'合上资料，用自己的话解释“{c["title"]}”，并给出一个例子。')
        # Source and exact range take precedence over legacy broad pointIds.
        points=[p['id'] for p in study['knowledge'] if p['source']==c['source'] and c['start']<=p['page']<=c['end'] and p.get('status')!='needs-review']
        chapters[c['id']]={**n,'pointIds':points,'table':TABLES.get(c['id']),'case':CASES.get(c['id']),'authored':c['id'] in notes}
    editions={s['id']:[] for s in study['sources']}
    for p in pages['pages']:
        if p['s'] in editions: editions[p['s']].append(dict(p=p['p'],blocks=clean_blocks(p['t'])))
    return chapters,editions
